#!/usr/bin/env python3
"""Generate the warehouse SDF world AND a matching ground-truth occupancy map.

Both are produced from the same list of boxes, so the pre-built map is
pixel-aligned with the simulator (world frame == map frame, robot spawns at 0,0).
SLAM Toolbox also puts its map origin at the robot's start pose, so a map you
build yourself with SLAM is interchangeable with this one.

Usage:
  generate_world_and_map.py --world worlds/warehouse.sdf --map ../amr_bringup/maps/warehouse
"""
import argparse
import math
import os

WALL_H = 1.0
# (name, cx, cy, sx, sy, height)
BOXES = [
    # outer walls (inner free space x in [-9.9, 9.9], y in [-6.9, 6.9])
    ('wall_north', 0.0, 7.0, 20.2, 0.2, WALL_H),
    ('wall_south', 0.0, -7.0, 20.2, 0.2, WALL_H),
    ('wall_east', 10.0, 0.0, 0.2, 14.0, WALL_H),
    ('wall_west', -10.0, 0.0, 0.2, 14.0, WALL_H),
    # partitions at x = 0 (central gap y in [-4, 4])
    ('partition_n', 0.0, 5.5, 0.2, 3.0, WALL_H),
    ('partition_s', 0.0, -5.5, 0.2, 3.0, WALL_H),
    # east room wall with a 1.5 m door (gap x in [6.5, 8.0])
    ('room_wall_a', 5.75, 1.5, 1.5, 0.2, WALL_H),
    ('room_wall_b', 9.0, 1.5, 2.0, 0.2, WALL_H),
    # shelving rows
    ('shelf_nw', -6.0, 4.0, 3.0, 0.6, 1.2),
    ('shelf_sw', -6.0, -4.0, 3.0, 0.6, 1.2),
    ('shelf_ne', 6.0, 4.0, 3.0, 0.6, 1.2),
    ('shelf_se', 6.0, -4.0, 3.0, 0.6, 1.2),
    # pillars
    ('pillar_1', 3.0, 2.5, 0.4, 0.4, 2.0),
    ('pillar_2', -3.5, 2.5, 0.4, 0.4, 2.0),
    ('pillar_3', -3.5, -2.5, 0.4, 0.4, 2.0),
    ('pillar_4', 3.0, -2.5, 0.4, 0.4, 2.0),
    # crates
    ('crate_1', -8.5, 5.5, 1.0, 1.0, 0.8),
    ('crate_2', -8.0, -5.5, 1.0, 1.0, 0.8),
    ('crate_3', 8.5, -5.5, 1.0, 1.0, 0.8),
]

COLORS = {
    'wall': '0.75 0.75 0.72 1', 'partition': '0.75 0.75 0.72 1', 'room': '0.75 0.75 0.72 1',
    'shelf': '0.20 0.45 0.75 1', 'pillar': '0.85 0.75 0.20 1', 'crate': '0.55 0.35 0.15 1',
}

MAP_RES = 0.05
MAP_X0, MAP_Y0 = -10.5, -7.5
MAP_W, MAP_H = 420, 300   # 21 m x 15 m
INTERIOR = (-9.9, 9.9, -6.9, 6.9)


def color_of(name):
    for k, v in COLORS.items():
        if name.startswith(k):
            return v
    return '0.7 0.7 0.7 1'


def world_sdf():
    elems = []
    for name, cx, cy, sx, sy, h in BOXES:
        c = color_of(name)
        elems.append(f"""
        <collision name="{name}_collision">
          <pose>{cx} {cy} {h / 2} 0 0 0</pose>
          <geometry><box><size>{sx} {sy} {h}</size></box></geometry>
        </collision>
        <visual name="{name}_visual">
          <pose>{cx} {cy} {h / 2} 0 0 0</pose>
          <geometry><box><size>{sx} {sy} {h}</size></box></geometry>
          <material><ambient>{c}</ambient><diffuse>{c}</diffuse></material>
        </visual>""")
    body = ''.join(elems)
    return f"""<?xml version="1.0" ?>
<!-- AUTO-GENERATED by amr_gazebo/scripts/generate_world_and_map.py - edit the script, not this file -->
<sdf version="1.9">
  <world name="warehouse">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.8 0.85 0.9 1</background>
      <grid>false</grid>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry>
          <material><ambient>0.45 0.45 0.45 1</ambient><diffuse>0.55 0.55 0.55 1</diffuse></material>
        </visual>
      </link>
    </model>

    <model name="warehouse_structure">
      <static>true</static>
      <link name="link">{body}
      </link>
    </model>
  </world>
</sdf>
"""


def build_grid():
    # 205 = unknown, 254 = free, 0 = occupied   (map_server trinary convention)
    grid = [[205] * MAP_W for _ in range(MAP_H)]
    for r in range(MAP_H):
        y = MAP_Y0 + (r + 0.5) * MAP_RES
        for c in range(MAP_W):
            x = MAP_X0 + (c + 0.5) * MAP_RES
            if INTERIOR[0] <= x <= INTERIOR[1] and INTERIOR[2] <= y <= INTERIOR[3]:
                grid[r][c] = 254
    for _, cx, cy, sx, sy, _ in BOXES:
        x0, x1 = cx - sx / 2, cx + sx / 2
        y0, y1 = cy - sy / 2, cy + sy / 2
        c0 = max(0, int(math.floor((x0 - MAP_X0) / MAP_RES)))
        c1 = min(MAP_W - 1, int(math.ceil((x1 - MAP_X0) / MAP_RES)) - 1)
        r0 = max(0, int(math.floor((y0 - MAP_Y0) / MAP_RES)))
        r1 = min(MAP_H - 1, int(math.ceil((y1 - MAP_Y0) / MAP_RES)) - 1)
        for r in range(r0, r1 + 1):
            for c in range(c0, c1 + 1):
                grid[r][c] = 0
    return grid


def write_map(prefix):
    grid = build_grid()
    pgm = prefix + '.pgm'
    with open(pgm, 'wb') as f:
        f.write(f'P5\n# warehouse ground-truth map\n{MAP_W} {MAP_H}\n255\n'.encode())
        for r in reversed(range(MAP_H)):          # image row 0 = max y
            f.write(bytes(grid[r]))
    with open(prefix + '.yaml', 'w') as f:
        f.write(f"""image: {os.path.basename(pgm)}
mode: trinary
resolution: {MAP_RES}
origin: [{MAP_X0}, {MAP_Y0}, 0.0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
""")
    return grid


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--world', required=True)
    ap.add_argument('--map', required=True, help='output prefix, e.g. maps/warehouse')
    a = ap.parse_args()
    with open(a.world, 'w') as f:
        f.write(world_sdf())
    write_map(a.map)
    print(f'wrote {a.world}, {a.map}.pgm, {a.map}.yaml')


if __name__ == '__main__':
    main()
